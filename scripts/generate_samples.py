#!/usr/bin/env python3
"""Generate small, synthetic MIT fixtures. They are not a real robot model."""
from pathlib import Path
import math
ROOT=Path(__file__).resolve().parents[1]
STL='''solid synthetic_triangle
facet normal 0 0 1
 outer loop
 vertex -0.1 -0.1 0
 vertex 0.1 -0.1 0
 vertex 0 0.1 0.2
 endloop
endfacet
endsolid synthetic_triangle
'''
DAE='''<?xml version="1.0" encoding="utf-8"?>
<COLLADA xmlns="http://www.collada.org/2005/11/COLLADASchema" version="1.4.1"><asset><contributor><author>qqfly</author></contributor><created>2026-11-08T00:00:00Z</created><modified>2026-11-08T00:00:00Z</modified><unit meter="1" name="meter"/><up_axis>Z_UP</up_axis></asset><library_geometries><geometry id="link"><mesh><source id="positions"><float_array id="array" count="9">-0.1 -0.1 0 0.1 -0.1 0 0 0.1 0.2</float_array><technique_common><accessor source="#array" count="3" stride="3"><param name="X" type="float"/><param name="Y" type="float"/><param name="Z" type="float"/></accessor></technique_common></source><vertices id="vertices"><input semantic="POSITION" source="#positions"/></vertices><triangles count="1"><input semantic="VERTEX" source="#vertices" offset="0"/><p>0 1 2</p></triangles></mesh></geometry></library_geometries><library_visual_scenes><visual_scene id="scene"><node id="node"><instance_geometry url="#link"/></node></visual_scene></library_visual_scenes><scene><instance_visual_scene url="#scene"/></scene></COLLADA>
'''
def main():
 model=ROOT/'data/models/sample_robot'
 for kind in ['visual','collision']:
  folder=model/'meshes'/kind;folder.mkdir(parents=True,exist_ok=True)
  for name in ['base_link']+[f'link_{i}' for i in range(1,7)]:
   (folder/(name+('.dae' if kind=='visual' else '.stl'))).write_text(DAE if kind=='visual' else STL)
 points=ROOT/'data/models/pointcloud/synthetic_cloud.pcd';points.parent.mkdir(parents=True,exist_ok=True)
 points.write_text('''# Synthetic fixture, Copyright (c) 2026 qqfly, MIT
VERSION .7
FIELDS x y z
SIZE 4 4 4
TYPE F F F
COUNT 1 1 1
WIDTH 1000
HEIGHT 1
VIEWPOINT 0 0 0 1 0 0 0
POINTS 1000
DATA ascii
'''+''.join(f'{(i%10)/10:.1f} {((i//10)%10)/10:.1f} {(i//100)/10:.1f}\n' for i in range(1000)))
 (ROOT/'data/README.md').write_text('# Synthetic fixtures\n\nGenerated by `python3 scripts/generate_samples.py`; MIT, copyright 2026 qqfly. No measurements, real point clouds, or manufacturer robot meshes. The six-axis scene is a visualization fixture, not an accurate physical robot.\n')
if __name__=='__main__':main()
