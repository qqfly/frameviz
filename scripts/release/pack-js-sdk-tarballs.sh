#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUT_DIR="${1:-$ROOT_DIR/dist/frameviz-js-sdk}"
if [[ "$OUT_DIR" != /* ]]; then
  OUT_DIR="$ROOT_DIR/$OUT_DIR"
fi

sha256_file() {
  local file="$1"
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$file" | awk '{print $1}'
  else
    shasum -a 256 "$file" | awk '{print $1}'
  fi
}

echo "[pack-js-sdk] root: $ROOT_DIR"
echo "[pack-js-sdk] out : $OUT_DIR"

mkdir -p "$OUT_DIR"

# Do not wipe OUT_DIR because release pipelines may already place runtime
# artifacts there. Only clean files generated by this script.
rm -f "$OUT_DIR"/frameviz-protocol-*.tgz
rm -f "$OUT_DIR"/frameviz-core-*.tgz
rm -f "$OUT_DIR"/frameviz-vue-*.tgz
rm -f "$OUT_DIR/JS_SDK_SHA256SUMS.txt" "$OUT_DIR/JS_SDK_MANIFEST.json"

echo "[pack-js-sdk] build @frameviz/protocol"
pnpm -C "$ROOT_DIR/packages/frameviz-protocol" build
find "$ROOT_DIR/packages/frameviz-protocol/dist" -name "*.map" -type f -delete || true

echo "[pack-js-sdk] build @frameviz/core"
pnpm -C "$ROOT_DIR/packages/frameviz-core" build
find "$ROOT_DIR/packages/frameviz-core/dist" -name "*.map" -type f -delete || true

echo "[pack-js-sdk] build @frameviz/vue"
pnpm -C "$ROOT_DIR/packages/frameviz-vue" build
find "$ROOT_DIR/packages/frameviz-vue/dist" -name "*.map" -type f -delete || true

echo "[pack-js-sdk] pack @frameviz/protocol"
pnpm -C "$ROOT_DIR/packages/frameviz-protocol" pack --pack-destination "$OUT_DIR"

echo "[pack-js-sdk] pack @frameviz/core"
pnpm -C "$ROOT_DIR/packages/frameviz-core" pack --pack-destination "$OUT_DIR"

echo "[pack-js-sdk] pack @frameviz/vue"
pnpm -C "$ROOT_DIR/packages/frameviz-vue" pack --pack-destination "$OUT_DIR"

echo "[pack-js-sdk] write checksums"
: > "$OUT_DIR/JS_SDK_SHA256SUMS.txt"
shopt -s nullglob
tarballs=("$OUT_DIR"/*.tgz)
if [ "${#tarballs[@]}" -eq 0 ]; then
  echo "[pack-js-sdk] error: no SDK tarballs found in $OUT_DIR" >&2
  exit 1
fi
for tarball in "${tarballs[@]}"; do
  checksum="$(sha256_file "$tarball")"
  echo "$checksum  $(basename "$tarball")" >> "$OUT_DIR/JS_SDK_SHA256SUMS.txt"
done
shopt -u nullglob

echo "[pack-js-sdk] write manifest"
ROOT_DIR="$ROOT_DIR" OUT_DIR="$OUT_DIR" python3 <<'PY'
import glob
import hashlib
import json
import os
from datetime import datetime, timezone
from pathlib import Path

root = Path(os.environ["ROOT_DIR"])
out = Path(os.environ["OUT_DIR"])
version_json = json.loads((root / "version.json").read_text())

entries = []
for tgz in sorted(out.glob("*.tgz")):
    h = hashlib.sha256()
    with tgz.open("rb") as f:
        while True:
            chunk = f.read(1024 * 1024)
            if not chunk:
                break
            h.update(chunk)
    entries.append(
        {
            "file": tgz.name,
            "sha256": h.hexdigest(),
        }
    )

manifest = {
    "protocol_version": version_json.get("protocol_version"),
    "generated_at_utc": datetime.now(timezone.utc).isoformat(),
    "artifacts": entries,
}
(out / "JS_SDK_MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n")
PY

echo "[pack-js-sdk] done"
echo "[pack-js-sdk] files:"
ls -1 "$OUT_DIR"
